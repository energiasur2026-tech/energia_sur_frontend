const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/components/lumi/lumi-state.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const stateModule = { exports: {} };
new Function('exports', 'module', compiled)(stateModule.exports, stateModule);
const { resolveLumiState } = stateModule.exports;
const normal = { events: [], busy: false, success: false, greeting: false };
const event = { id: 'fixture', type: 'unusual_power', at: '2026-11-08T12:00:00Z', evidence: 'Test fixture only', question: null, read: false, userLabels: [] };
const resolve = (options) => resolveLumiState({ ...normal, ...options });
assert.equal(resolve({}), 'idle', 'No operation or notification must remain idle');
assert.equal(resolve({ greeting: true }), 'greeting');
assert.equal(resolve({ busy: true }), 'analyzing');
assert.equal(resolve({ success: true }), 'success');
assert.equal(resolve({ events: [{ ...event, question: 'Test question' }] }), 'question');
assert.equal(resolve({ events: [event] }), 'alert');
assert.equal(resolve({ busy: true, events: [{ ...event, question: 'Test question' }] }), 'analyzing');
assert.equal(resolve({ busy: true, success: true, events: [{ ...event, type: 'voltage' }] }), 'alert', 'Electrical warnings outrank loading and success');
assert.equal(resolve({ events: [{ ...event, severity: 'CRITICAL' }, { ...event, question: 'Test question' }] }), 'alert');
assert.equal(resolve({ events: [{ ...event, read: true, question: 'Test question' }] }), 'idle', 'Read events must not keep drawing attention');
assert.equal(resolve({ events: [{ ...event, question: 'Test question', userLabels: ['Plancha'] }] }), 'alert', 'Answered questions are no longer question state');
console.log('11 Lumi state checks passed. Fixtures are never imported by production.');
